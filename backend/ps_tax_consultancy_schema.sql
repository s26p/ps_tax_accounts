-- Atomically allocate the next invoice number. The sequence only moves forward.
CREATE OR REPLACE FUNCTION allocate_pstc_invoice_number(p_organization_id TEXT)
RETURNS TEXT
LANGUAGE plpgsql
AS $$
DECLARE
    allocated_number BIGINT;
    number_text TEXT;
BEGIN
    INSERT INTO invoice_sequence AS seq (organization_id, next_number)
    VALUES (p_organization_id, 2)
    ON CONFLICT (organization_id)
    DO UPDATE SET
        next_number = seq.next_number + 1,
        updated_at = NOW()
    RETURNING next_number - 1 INTO allocated_number;

    number_text := allocated_number::TEXT;
    IF LENGTH(number_text) < 4 THEN
        number_text := LPAD(number_text, 4, '0');
    END IF;

    RETURN 'PSTC-INV-' || number_text;
END;
$$;

